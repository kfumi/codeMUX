import { describe, expect, it } from 'vitest';

import { formatTokenCount } from './formatTokenCount';

describe('formatTokenCount', () => {
  it.each([
    [0, '0'],
    [8420, '8420'],
    [9999, '9999'],
    [10_000, '1万'],
    [17_722, '1.8万'],
    [360_000, '36万'],
    [3_600_000, '360万'],
    [36_000_000, '3600万'],
    [36_400_000, '3640万'],
    [99_950_000, '9995万'],
    [99_995_000, '9999.5万'],
    [99_999_499, '9999.9万'],
    [99_999_500, '1亿'],
    [100_000_000, '1亿'],
    [120_000_000, '1.2亿'],
    [200_000_000, '2亿'],
    [1_436_000_000, '14.36亿'],
    [12_345_678_900, '123.46亿'],
  ])('%d -> %s', (input, expected) => {
    expect(formatTokenCount(input)).toBe(expected);
  });
});
